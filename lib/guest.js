export function metaFor(key, lang, path, SITE, LANGS) {
  const m = PAGEMETA[key][lang];
  const languages = Object.fromEntries(LANGS.map((l) => [l, `${SITE}/${l}/${path}`]));
  languages["x-default"] = `${SITE}/fa/${path}`;
  return {
    title: m.title,
    description: m.desc,
    alternates: { canonical: `${SITE}/${lang}/${path}`, languages },
    openGraph: { title: m.title, description: m.desc, url: `${SITE}/${lang}/${path}`, siteName: "Pissoo", type: "website", images: [{ url: "/hero/hero-1.jpg" }] },
  };
}

export function dur(min, lang) {
  const d = G[lang].dur; const nfmt = (n) => Number(n).toLocaleString({ fa: "fa-IR", en: "en-US", ar: "ar-EG" }[lang], { useGrouping: false });
  const h = Math.floor(min / 60); const m = min % 60;
  if (!h) return `${nfmt(m)} ${d.m}`;
  if (!m) return `${nfmt(h)} ${d.h}`;
  return `${nfmt(h)} ${d.h}${d.and}${nfmt(m)} ${d.m}`;
}
